class GlobalPngIcon:
    BASE_PATH = Path(__file__).parent

    def __new__(cls, *args, **kwargs):
        if not hasattr(cls, '_instance'):
            cls._instance = super(GlobalPngIcon, cls).__new__(cls, *args, **kwargs)
        return cls._instance

    def get(self, name: PngIcon, size: PngSize, color: PngColor) -> QPixmap:
        size_map = {
            PngSize.SMALL: "png",
            PngSize.MEDIUM: "png@3x",
            PngSize.LARGE: "png@5x",
        }
        color_map = {
            PngColor.WHITE: "white",
            PngColor.BLACK: "black",
        }

        size_dir = size_map.get(size)
        color_dir = color_map.get(color)

        if not size_dir or not color_dir:
            raise ValueError("Invalid size or color value")
        print(str(self.BASE_PATH.joinpath(size_dir, color_dir, f"{name.value}.png")))
        return QPixmap(str(self.BASE_PATH.joinpath(size_dir, color_dir, f"{name.value}.png")))


